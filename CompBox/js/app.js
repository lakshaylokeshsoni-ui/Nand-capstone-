  function boxCheck(asm, b, label) {
    const c = machine(asm); const bad = [];
    c.setKey(0); c.run(4000);
    for (let r = b.row - 1; r <= b.row + b.h; r++) for (let w = 0; w <= b.w; w++) if (word(c, r, w) !== 0) bad.push('idle not white');
    c.setKey(65); c.run(8000);
    for (let r = b.row; r < b.row + b.h; r++) for (let w = 0; w < b.w; w++) if (word(c, r, w) !== -1) bad.push(`black missing at row ${r} word ${w}`);
    const guards = [[b.row - 1, 0], [b.row + b.h, 0], [b.row, b.w], [b.row + b.h - 1, b.w]];
    guards.forEach(g => { if (word(c, g[0], g[1]) !== 0) bad.push(`guard word (row ${g[0]}, word ${g[1]}) was painted`); });
    let painted = 0; for (let i = 0; i < 8192; i++) if (c.ram[SCREEN + i] !== 0) painted++;
    if (painted !== b.h * b.w) bad.push(`painted ${painted} words, expected ${b.h * b.w}`);
    c.setKey(0); c.run(8000);
    painted = 0; for (let i = 0; i < 8192; i++) if (c.ram[SCREEN + i] !== 0) painted++;
    if (painted !== 0) bad.push('box not cleared after release');
    return bad.length ? { ok: false, d: bad.slice(0, 3).join('; ') } : { ok: true, d: `${label}: ${b.h} rows × ${b.w} words appear on key down, disappear on key up, nothing else touched` };
  }

